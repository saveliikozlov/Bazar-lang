'use strict';
const test = require('node:test');
const assert = require('node:assert');
const path = require('path');
const { execFileSync } = require('child_process');
const { complete, isInComment, declaredNames, ENTRIES } = require('../../src/completion');

const labels = (items) => items.map((i) => i.label);
const at = (prefix, text = prefix) => complete(prefix, text, prefix.length);

test("empty prefix offers all language constructs", () => {
  const found = labels(at(''));
  for (const expected of ['желєзобетонно', 'зуб даю', 'мутна тєма', 'перевзувся … тепер', 'якшо реально', 'а нє', 'отакої', 'базарь',
    'всьо розходимось', 'чутки:', 'тіпа', 'це', 'дрібняк', 'крупняк', 'базар', 'реально', 'гон', 'плюс', 'мінус', 'на',
    'ділити на', 'рівно', 'не рівно', 'більше', 'менше', 'і ше', 'або']) {
    assert.ok(found.includes(expected), `missing ${expected}`);
  }
});

test("Cyrillic prefixes filter suggestions and replace only the typed word", () => {
  const [item] = at('  зу').filter((i) => i.label === 'зуб даю');
  assert.strictEqual(item.replaceLength, 2);
  assert.strictEqual(item.filterText, 'зуб даю');
  assert.ok(!labels(at('  зу')).includes('мутна тєма'));
});

test("phrase prefix зуб д does not duplicate зуб", () => {
  const item = at('зуб д').find((i) => i.label === 'зуб даю');
  assert.strictEqual(item.replaceLength, 'зуб д'.length);
  const spaced = at('  зуб   ').find((i) => i.label === 'зуб даю');
  assert.strictEqual(spaced.replaceLength, 'зуб   '.length);
  assert.ok(!labels(at('зуб д')).includes('мутна тєма'));
});

test("phrase within a line replaces only the partial phrase", () => {
  const item = at('базарь 1 не р').find((i) => i.label === 'не рівно');
  assert.strictEqual(item.replaceLength, 'не р'.length);
  const exit = at('всьо р').find((i) => i.label === 'всьо розходимось');
  assert.strictEqual(exit.replaceLength, 'всьо р'.length);
});

test("whole words: word suffixes do not match phrases", () => {
  // мізузуб д does not contain a separate зуб word
  assert.ok(!labels(at('мізузуб д')).includes('зуб даю'));
});

test("completion is disabled inside comments", () => {
  assert.deepStrictEqual(at('чутки: зуб'), []);
  assert.deepStrictEqual(at('базарь 1 чутки: 😀 мінус'), []);
  assert.ok(at('чутки').length > 0); // no colon yet: this is still a word, not a comment
  assert.ok(at('мічутки: з').length > 0); // мічутки is a different word, not a comment marker
  assert.strictEqual(isInComment('xчутки: a'), false);
  assert.strictEqual(isInComment('x чутки: a'), true);
});

test("declaration and condition snippets expand into valid programs", () => {
  const python = process.env.BAZAR_PYTHON || 'python3';
  const script = path.join(__dirname, '..', '..', 'backend', 'bazar_bridge.py'); // generated by npm run sync-backend
  const expand = (snippet) => snippet
    .replace(/\$\{\d\|([^,}]+)[^}]*\}/g, '$1')
    .replace(/\$\{\d:([^}]*)\}/g, '$1')
    .replace(/\\t|\t/g, '  ');
  for (const entry of ENTRIES.filter((e) => e.kind === 'statement')) {
    const program = expand(entry.snippet) + '\n';
    if (['а нє', 'отакої'].includes(entry.label)) continue; // condition fragments are not standalone programs
    if (entry.label === 'чутки:') continue;
    const out = execFileSync(python, ['-I', script], { input: JSON.stringify({ text: program }) }).toString();
    assert.strictEqual(JSON.parse(out).ok, true, `${entry.label}: ${JSON.stringify(program)} -> ${out}`);
  }
});

test("declared names exclude comments and the name being declared", () => {
  const text = 'зуб даю баланс тіпа дрібняк це 1\nмутна тєма лічба тіпа крупняк це 2 чутки: зуб даю прихований\nбазарь ба';
  const names = declaredNames(text, -1);
  assert.deepStrictEqual(names.sort(), ['баланс', 'лічба']);
  const items = complete('базарь ба', text, text.length);
  assert.ok(labels(items).includes('баланс'));
  assert.ok(!labels(items).includes('прихований'));
  const variable = items.find((i) => i.label === 'баланс');
  assert.strictEqual(variable.replaceLength, 2);
  // suppress variable suggestions while a new name is being declared
  const decl = 'зуб даю баланс тіпа дрібняк це 1\nзуб даю ба';
  assert.ok(!labels(complete('зуб даю ба', decl, decl.length)).includes('баланс'));
});

test("constant names are offered after declaration", () => {
  const text = 'желєзобетонно ЛІМІТ тіпа дрібняк це 10\nбазарь ЛІ';
  assert.deepStrictEqual(declaredNames(text, -1), ['ЛІМІТ']);
  assert.ok(labels(complete('базарь ЛІ', text, text.length)).includes('ЛІМІТ'));
});

test("a partially typed declaration name does not suggest itself", () => {
  const text = 'базарь 1\nперевзувся лі';
  assert.ok(!labels(complete('перевзувся лі', text, text.length)).includes('лі'));
});
