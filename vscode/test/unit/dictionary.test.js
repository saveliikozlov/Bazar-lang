'use strict';
const test = require('node:test');
const assert = require('node:assert');
const fs = require('fs');
const path = require('path');
const {
  ENTRIES, PHRASES, getEntry, findAt, tokenize, hoverMarkdown, referenceMarkdown,
} = require('../../src/dictionary');
const { complete, ENTRIES: COMPLETION_ENTRIES } = require('../../src/completion');

const grammar = fs.readFileSync(path.join(__dirname, '..', '..', '..', 'grammar.ebnf'), 'utf8');
const flatGrammar = grammar.replace(/\s+/g, ' ');

const ruleBody = (name) => {
  const match = grammar.match(new RegExp(`^${name} = ([^;]*);`, 'm'));
  assert.ok(match, `missing grammar rule ${name}`);
  return match[1];
};
const quotedWords = (body) => [...body.matchAll(/"([^"]+)"/g)].map((m) => m[1]);

const KEYWORDS = quotedWords(ruleBody('keyword'));
const hit = (line, character) => findAt(line, character);
const idAt = (line, character) => { const h = hit(line, character); return h && h.entry.id; };
const rangeAt = (line, character) => { const h = hit(line, character); return h && [h.start, h.end]; };

test("grammar: all 32 keywords have individual dictionary entries", () => {
  assert.strictEqual(KEYWORDS.length, 32);
  for (const word of KEYWORDS) {
    const entry = getEntry(word);
    assert.ok(entry, `missing dictionary entry ${word}`);
    assert.deepStrictEqual(entry.words, [word]);
    assert.ok(['keyword', 'fragment'].includes(entry.kind), word);
  }
  const reserved = quotedWords(ruleBody('reserved_word'));
  assert.ok(reserved.includes('чутки'));
  assert.strictEqual(getEntry('чутки:').kind, 'comment');
});

test("phrases contain reserved words and match grammar token sequences", () => {
  assert.deepStrictEqual(PHRASES.map((p) => p.id).sort(), ['а нє', 'всьо розходимось', 'ділити на', 'зуб даю', 'і ше', 'мутна тєма', 'не рівно', 'якшо реально'].sort());
  for (const phrase of PHRASES) {
    for (const w of phrase.words) assert.ok(KEYWORDS.includes(w), w);
    assert.ok(flatGrammar.includes(phrase.words.map((w) => `"${w}"`).join(', ')), phrase.id);
  }
  for (const entry of ENTRIES.filter((e) => e.kind === 'fragment')) {
    const owner = getEntry(entry.partOf);
    assert.ok(owner && owner.kind === 'phrase' && owner.words.includes(entry.id), entry.id);
  }
});

test("dictionary productions are verbatim grammar.ebnf fragments", () => {
  for (const entry of ENTRIES) {
    for (const production of entry.productions || []) {
      assert.ok(flatGrammar.includes(production), `${entry.id}: ${production}`);
    }
  }
});

test("each entry has a meaning, syntax, and example through its phrase if needed", () => {
  for (const entry of ENTRIES) {
    assert.ok(entry.meaning.length > 20, entry.id);
    const source = entry.partOf ? getEntry(entry.partOf) : entry;
    assert.ok(source.productions.length && source.syntax && source.example, entry.id);
  }
});

test("dictionary examples are valid Bazar syntax", () => {
  const { execFileSync } = require('child_process');
  const script = path.join(__dirname, '..', '..', 'backend', 'bazar_bridge.py'); // generated by npm run sync-backend
  for (const entry of ENTRIES.filter((e) => e.example)) {
    const out = execFileSync(process.env.BAZAR_PYTHON || 'python3', ['-I', script], { input: JSON.stringify({ text: `${entry.example}\n` }) }).toString();
    assert.strictEqual(JSON.parse(out).ok, true, `${entry.id}: ${out}`);
  }
});

test("phrase components do not suggest standalone syntax", () => {
  for (const entry of ENTRIES.filter((e) => e.kind === 'fragment')) {
    assert.strictEqual(entry.syntax, undefined);
    const md = hoverMarkdown(entry);
    assert.ok(md.includes('This word cannot be used on its own'), entry.id);
    assert.ok(md.includes('phrase component'), entry.id);
  }
});

test("hover: any word matches the longest phrase with a full phrase range", () => {
  const line = 'зуб даю x тіпа дрібняк це 1';
  assert.strictEqual(idAt(line, 0), 'зуб даю');
  assert.strictEqual(idAt(line, 2), 'зуб даю');
  assert.strictEqual(idAt(line, 5), 'зуб даю');
  assert.deepStrictEqual(rangeAt(line, 5), [0, 7]);
  assert.strictEqual(idAt(line, 3), null); // space
  assert.strictEqual(idAt(line, 7), null);
  assert.strictEqual(idAt(line, 8), null); // x is an identifier
  assert.strictEqual(idAt(line, 10), 'тіпа');
  assert.strictEqual(idAt(line, 16), 'дрібняк');
  assert.strictEqual(idAt(line, 24), 'це');
  assert.strictEqual(idAt(line, 26), null); // number
});

test("hover: spaces and tabs separate phrase words but newlines do not", () => {
  assert.deepStrictEqual(rangeAt('зуб \t  даю', 8), [0, 10]);
  assert.strictEqual(idAt('мутна\tтєма', 7), 'мутна тєма');
  assert.strictEqual(idAt('зуб\nдаю', 0), 'зуб'); // separate lines cannot form a phrase
  assert.strictEqual(idAt('зуб\r\nдаю', 0), 'зуб');
  assert.strictEqual(idAt('зуб (даю', 0), 'зуб');
  assert.strictEqual(idAt('зуб (даю', 6), 'даю');
  assert.strictEqual(idAt('зуб а даю', 0), 'зуб');
});

test("hover: exact words, case, apostrophes, and adjacent word characters", () => {
  for (const word of ['зуби', 'базарний', 'наш', 'якшоб', 'отакоїж', 'дрібняк_2', 'Зуб', 'БАЗАРЬ', 'зуб1', '1зуб', 'xчутки', 'мінусик', "на'ш", 'аʼб']) {
    assert.strictEqual(hit(word, 1), null, word);
    assert.strictEqual(hit(`базарь ${word}`, 8), null, word);
  }
  assert.strictEqual(hit('зуб' + 'a'.repeat(3), 0), null);
  assert.strictEqual(idAt('(базарь)', 1), 'базарь');
  assert.strictEqual(idAt('мінус(мінус', 0), 'мінус');
  assert.strictEqual(hit('тiпа', 0), null); // Latin i
  assert.strictEqual(hit('тіпa', 0), null); // final Latin a
  assert.strictEqual(idAt('і ше', 0), 'і ше');
  assert.strictEqual(hit('и ше', 0), null); // и is not і
  assert.strictEqual(idAt('и ше', 2), 'ше');
});

test("hover: preceding emoji shifts the UTF-16 range by two units", () => {
  const line = '😀 базарь 1';
  assert.deepStrictEqual(rangeAt(line, 3), [3, 9]);
  assert.strictEqual(idAt(line, 0), null);
  assert.strictEqual(idAt(line, 1), null);
  assert.strictEqual(idAt(line, 2), null);
  assert.strictEqual(idAt('😀😀зуб   даю', 4), 'зуб даю');
  assert.deepStrictEqual(rangeAt('😀😀зуб   даю', 4), [4, 13]);
});

test("comments: marker has documentation but body does not", () => {
  assert.strictEqual(idAt('чутки: зуб даю', 0), 'чутки:');
  assert.strictEqual(idAt('чутки: зуб даю', 5), 'чутки:'); // colon
  assert.deepStrictEqual(rangeAt('  чутки: зуб даю', 3), [2, 8]);
  assert.strictEqual(idAt('чутки: зуб даю', 7), null);
  assert.strictEqual(idAt('чутки: зуб даю', 8), null);
  assert.strictEqual(idAt('базарь 1 чутки: базарь', 0), 'базарь');
  assert.strictEqual(idAt('базарь 1 чутки: базарь', 16), null);
  assert.strictEqual(idAt('базарь 1 чутки: базарь', 10), 'чутки:');
  assert.strictEqual(idAt('чутки:зуб даю', 6), null);
  assert.strictEqual(idAt('зуб чутки: даю', 0), 'зуб');
  assert.strictEqual(idAt('зуб чутки: даю', 12), null);
  // without a colon, there is no comment; the word remains reserved
  assert.strictEqual(idAt('чутки зуб даю', 0), 'чутки:');
  assert.deepStrictEqual(rangeAt('чутки зуб даю', 0), [0, 5]);
  assert.strictEqual(idAt('чутки зуб даю', 6), 'зуб даю');
  assert.strictEqual(idAt('чутки : зуб', 0), 'чутки:');
  assert.deepStrictEqual(rangeAt('чутки : зуб', 0), [0, 5]);
  assert.strictEqual(hit('xчутки: a', 1), null);
  assert.strictEqual(hit('xчутки: a', 8), null);
  assert.deepStrictEqual(tokenize('a чутки: b').comment, { start: 2, end: 8 });
});

test("multiple roles: реально, мінус, на, and нє", () => {
  assert.strictEqual(idAt('якшо реально реально', 0), 'якшо реально');
  assert.strictEqual(idAt('якшо реально реально', 8), 'якшо реально');
  assert.deepStrictEqual(rangeAt('якшо реально реально', 8), [0, 12]);
  assert.strictEqual(idAt('якшо реально реально', 15), 'реально'); // literal
  assert.strictEqual(idAt('базарь реально', 8), 'реально');
  assert.strictEqual(idAt('якшо x', 0), 'якшо'); // incomplete phrase
  assert.strictEqual(getEntry('якшо').kind, 'fragment');
  assert.strictEqual(idAt('базарь 2 на 3', 9), 'на');
  assert.strictEqual(idAt('базарь 8 ділити на 2', 9), 'ділити на');
  assert.strictEqual(idAt('базарь 8 ділити на 2', 16), 'ділити на');
  assert.strictEqual(idAt('базарь 2 на ділити на 2', 9), 'на');
  assert.strictEqual(idAt('ділити', 0), 'ділити');
  assert.strictEqual(idAt('базарь 1 не рівно 2', 10), 'не рівно');
  assert.strictEqual(idAt('базарь не 2', 8), 'не');
  assert.strictEqual(idAt('базарь 1 рівно 1', 9), 'рівно');
  assert.strictEqual(idAt('а нє', 0), 'а нє');
  assert.strictEqual(idAt('нє', 0), 'нє');
  assert.strictEqual(idAt('а', 0), 'а');
  assert.strictEqual(idAt('базарь 1 і ше 2 і', 9), 'і ше');
  assert.strictEqual(idAt('базарь 1 і ше 2 і', 16), 'і');
  assert.strictEqual(idAt('мінус мінус 1', 0), 'мінус');
  assert.match(hoverMarkdown(getEntry('нє')), /not logical NOT/);
  assert.match(hoverMarkdown(getEntry('мінус')), /unary/i);
  assert.match(hoverMarkdown(getEntry('мінус')), /subtraction/);
  assert.match(hoverMarkdown(getEntry('реально')), /true/);
  assert.match(hoverMarkdown(getEntry('реально')), /якшо реально/);
  assert.match(hoverMarkdown(getEntry('на')), /ділити на/);
});

test("hover Markdown includes meaning, grammar, syntax, example, and no HTML/commands", () => {
  const md = hoverMarkdown(getEntry('зуб даю'));
  assert.match(md, /^\*\*зуб даю\*\* · multiword phrase/);
  assert.ok(md.includes('```ebnf\nimmutable_declaration = '));
  assert.ok(md.includes('```bazar\nзуб даю зарплата тіпа крупняк це 100\n```'));
  assert.ok(md.includes('**Syntax:**'));
  assert.ok(md.includes('types and mutability are not checked'));
  for (const entry of ENTRIES) {
    const text = hoverMarkdown(entry);
    assert.ok(!/<[a-z/]/i.test(text.replace(/```[\s\S]*?```/g, '')), entry.id);
    assert.ok(!text.includes('command:'), entry.id);
  }
});

test("full dictionary contains every entry from the same data", () => {
  const doc = referenceMarkdown();
  assert.match(doc, /^# Bazar Keyword Dictionary/);
  for (const entry of ENTRIES) {
    assert.ok(doc.includes(`### ${entry.id.replace(/[.-]/g, '\\$&')}\n`), entry.id);
    assert.ok(doc.includes(`\`\`\`bazar\n${(entry.partOf ? getEntry(entry.partOf) : entry).example}\n\`\`\``), entry.id);
    assert.ok(doc.includes((entry.partOf ? getEntry(entry.partOf) : entry).productions[0]), entry.id);
  }
  for (const word of KEYWORDS) assert.ok(doc.includes(`### ${word}\n`), word);
  assert.ok(doc.includes('### чутки:'));
});

test("completion: each construct has dictionary documentation", () => {
  const items = complete('', '', 0);
  for (const entry of COMPLETION_ENTRIES) {
    const item = items.find((i) => i.label === entry.label);
    assert.ok(item, entry.label);
    assert.ok(item.documentation && item.documentation.includes('**Grammar**'), entry.label);
  }
  const assignment = items.find((i) => i.label === 'перевзувся … тепер');
  assert.strictEqual(assignment.documentation, hoverMarkdown(getEntry('перевзувся')));
  assert.strictEqual(items.find((i) => i.label === 'якшо реально … а нє').documentation, hoverMarkdown(getEntry('якшо реально')));
  assert.strictEqual(items.find((i) => i.label === 'ділити на').documentation, hoverMarkdown(getEntry('ділити на')));
  assert.strictEqual(items.find((i) => i.label === 'чутки:').documentation, hoverMarkdown(getEntry('чутки:')));
});

test("documentation preserves insertion behavior and excludes variable descriptions", () => {
  const text = 'зуб даю баланс тіпа дрібняк це 1\nбазарь ба';
  const items = complete('базарь ба', text, text.length);
  const variable = items.find((i) => i.label === 'баланс');
  assert.strictEqual(variable.documentation, undefined);
  const base = complete('зуб д', 'зуб д', 5).find((i) => i.label === 'зуб даю');
  assert.strictEqual(base.replaceLength, 5);
  assert.ok(base.insertText.startsWith('зуб даю ${1:name} тіпа'));
});
